// Helper to generate realistic historical readings for initial load
function generateHistory(
  baseLevel: number, 
  maxDepth: number, 
  baseRain: number, 
  isBlockedTrend: boolean = false
): SensorReading[] {
  const readings: SensorReading[] = [];
  const now = Date.now();
  const stepMs = 90 * 1000; // 90 seconds per point, 20 points = 30 minutes

  for (let i = 19; i >= 0; i--) {
    const time = new Date(now - i * stepMs);
    const timeLabel = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    
    // Natural jitter
    const rainNoise = Math.max(0, baseRain + (Math.sin(i / 3) * 4) + (Math.random() * 2 - 1));
    let level = baseLevel;
    
    if (isBlockedTrend) {
      // In blocked trend, level steadily climbed over the 30 minutes
      const progression = (20 - i) / 20;
      level = baseLevel * 0.4 + (baseLevel * 0.6 * progression) + (Math.random() * 2 - 1);
    } else {
      level = baseLevel + Math.sin(i / 2) * 3 + (Math.random() * 2 - 1);
    }

    const waterLevelCm = Math.max(2, Math.min(maxDepth, Math.round(level)));
    const capacityPercent = Math.min(100, Math.round((waterLevelCm / maxDepth) * 100));
    const flowVelocity = isBlockedTrend 
      ? Math.max(0.1, Number((1.8 - (capacityPercent / 70)).toFixed(2)))
      : Math.max(0.4, Number((1.2 + (waterLevelCm / 80)).toFixed(2)));
    const discharge = Math.round(flowVelocity * 45 * (1 - (isBlockedTrend ? 0.65 : 0)));

    readings.push({
      timestamp: time.toISOString(),
      timeLabel,
      waterLevelCm,
      capacityPercent,
      flowVelocityMs: flowVelocity,
      dischargeRateLs: discharge,
      rainfallMmH: Number(rainNoise.toFixed(1)),
      predictedTrend: Math.min(maxDepth, Math.round(waterLevelCm + (isBlockedTrend ? 5 : -2))),
    });
  }
  return readings;
}

